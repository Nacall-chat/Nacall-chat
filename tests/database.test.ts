import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const a = '11111111-1111-4111-8111-111111111111';
const b = '22222222-2222-4222-8222-222222222222';
const c = '33333333-3333-4333-8333-333333333333';
test('migration PostgreSQL: isolamento, amizade, convites e limite de tokens', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema public,auth to authenticated,anon;
      grant execute on function auth.uid() to authenticated,anon;
      create publication supabase_realtime;`);
    await db.exec(await readFile(new URL('../supabase/migrations/202611020001_initial.sql', import.meta.url), 'utf8'));
    await db.query('insert into auth.users(id) values($1),($2),($3)', [a,b,c]);
    const as = async (id: string) => {
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
      await db.exec('set role authenticated');
    };
    await as(a);
    const server = (await db.query<{id:string}>("select public.create_server('Nossa turma') as id")).rows[0].id;
    const channels = (await db.query<{id:string;kind:string}>('select id,kind from public.channels')).rows;
    const text = channels.find(x=>x.kind==='text')!.id;
    assert.equal(channels.length,2);
    await db.query('insert into public.messages(channel_id,body) values($1,$2)', [text,'Olá turma']);
    const invite = (await db.query<{code:string}>('insert into public.invites(server_id) values($1) returning code', [server])).rows[0].code;
    await as(b);
    assert.equal((await db.query('select * from public.servers')).rows.length,0);
    assert.equal((await db.query('select * from public.channels')).rows.length,0);
    assert.equal((await db.query('select * from public.messages')).rows.length,0);
    await assert.rejects(db.query('insert into public.messages(channel_id,body) values($1,$2)', [text,'Invasão']));
    await assert.rejects(db.query("insert into public.channels(server_id,name,kind) values($1,'invadido','voice')", [server]));
    await db.query('select public.join_server($1)',[invite]);
    assert.equal((await db.query('select * from public.messages')).rows.length,1);
    await assert.rejects(db.query("insert into public.channels(server_id,name,kind) values($1,'sem cargo','voice')", [server]));
    await db.query('insert into public.friendships(sender_id,receiver_id) values($1,$2)',[b,a]);
    await db.query("update public.friendships set status='accepted'");
    assert.equal((await db.query<{status:string}>('select status from public.friendships')).rows[0].status,'pending','remetente não pode aceitar a própria solicitação');
    await assert.rejects(db.query('select public.open_dm($1)',[a]));
    await as(a);
    await db.query("update public.friendships set status='accepted'");
    const dm = (await db.query<{id:string}>('select public.open_dm($1) as id',[b])).rows[0].id;
    await db.query('insert into public.messages(dm_id,body) values($1,$2)',[dm,'Privado']);
    await as(b);
    assert.equal((await db.query('select * from public.messages where dm_id=$1',[dm])).rows.length,1);
    await db.query('delete from public.messages where dm_id=$1',[dm]);
    assert.equal((await db.query('select * from public.messages where dm_id=$1',[dm])).rows.length,1,'somente autor exclui');
    await as(c);
    assert.equal((await db.query('select * from public.dms')).rows.length,0);
    assert.equal((await db.query('select * from public.messages')).rows.length,0);
    assert.equal((await db.query('select * from public.invites')).rows.length,0);
    await assert.rejects(db.query('insert into public.messages(dm_id,body) values($1,$2)',[dm,'Invadindo DM']));
    for(let i=0;i<10;i++) assert.equal((await db.query<{ok:boolean}>('select public.allow_voice_token() as ok')).rows[0].ok,true);
    assert.equal((await db.query<{ok:boolean}>('select public.allow_voice_token() as ok')).rows[0].ok,false);
    await as(a);
    await db.query('delete from public.invites where code=$1',[invite]);
    await as(c);
    await assert.rejects(db.query('select public.join_server($1)',[invite]));
    await db.exec("reset role; set role anon");
    await assert.rejects(db.query('select public.create_server($1)',['Anônimo']));
  } finally { await db.close(); }
});
